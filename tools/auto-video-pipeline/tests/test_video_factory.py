import json
from pathlib import Path
import subprocess
import tempfile
import unittest
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from video_factory import (parse_srt, choose_windows, make_plan, render,
                           sha256, media_probe)


class VideoFactoryTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)

    def sample(self, secs=5):
        path = self.root / 'original.mp4'
        cmd = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
               '-f', 'lavfi', '-i', f'testsrc2=size=320x240:rate=15:duration={secs}',
               '-f', 'lavfi', '-i', f'sine=frequency=440:sample_rate=8000:duration={secs}',
               '-c:v', 'libx264', '-preset', 'ultrafast', '-pix_fmt', 'yuv420p',
               '-c:a', 'aac', '-shortest', str(path)]
        subprocess.run(cmd, check=True)
        return path

    def test_srt_multilingual(self):
        srt = self.root / 'a.srt'
        srt.write_text('1\n00:00:00,100 --> 00:00:01,200\nHello!\n\n'
                       '2\n00:00:02,000 --> 00:00:03,200\nBonjour!\n', encoding='utf-8')
        self.assertEqual([x['text'] for x in parse_srt(srt)], ['Hello!', 'Bonjour!'])

    def test_nonoverlap(self):
        options = choose_windows(55, [3, 10, 20, 30, 40], [250] * 55, [], count=5, window=10)
        self.assertGreaterEqual(len(options), 3)
        self.assertLessEqual(len(options), 5)
        for i, first in enumerate(options):
            for second in options[i+1:]:
                overlap = max(0, min(first['start']+10, second['start']+10) - max(first['start'], second['start']))
                self.assertLessEqual(overlap, 2.5)

    def test_plan_blocks_remote_url(self):
        with self.assertRaises(FileNotFoundError):
            make_plan('https://youtube.com/watch?v=xxxxxxxxxxx', self.root/'plan', 'HEMA', 'DRUZINA_ZS', 'Join')

    def test_render_blocks_unknown_or_fake_clearance(self):
        source = self.sample()
        planned = make_plan(source, self.root / 'planned', 'Original demo', 'OSVC', 'Learn more', count=1, window=3)
        self.assertEqual(planned['status'], 'CUT_PROPOSALS_NEED_REVIEW')
        spec = Path(planned['plan'])
        approval = self.root / 'approval.json'
        approval.write_text(json.dumps({'source_sha256': sha256(source), 'rights_status': 'unknown',
                                        'rights_basis': 'My own camera original',
                                        'people_consents_checked': True, 'music_rights_checked': True,
                                        'contains_minors': False}))
        with self.assertRaises(ValueError):
            render(spec, approval, self.root / 'drafts')
        approval.write_text(json.dumps({'source_sha256': 'bad', 'rights_status': 'owned',
                                        'rights_basis': 'My own camera original',
                                        'people_consents_checked': True, 'music_rights_checked': True,
                                        'contains_minors': False}))
        with self.assertRaises(ValueError):
            render(spec, approval, self.root / 'drafts')

    def test_end_to_end_real_mp4_review_only(self):
        source = self.sample()
        p = make_plan(source, self.root / 'planned', 'My original camera recording', 'DRUZINA_ZS',
                      'See club activities', count=1, window=3)
        approval = self.root / 'approval.json'
        approval.write_text(json.dumps({'source_sha256': sha256(source), 'rights_status': 'owned',
                                        'rights_basis': 'Synthetic test video generated by this test',
                                        'people_consents_checked': True, 'music_rights_checked': True,
                                        'contains_minors': False}))
        out = render(Path(p['plan']), approval, self.root / 'drafts')
        self.assertEqual(out['status'], 'MEDIA_RENDERED_REVIEW_REQUIRED')
        self.assertEqual(out['rendered'], 1)
        qa = json.loads(Path(out['qa']).read_text())
        self.assertFalse(qa['editorial_approved'])
        self.assertFalse(qa['published'])
        self.assertEqual((1080, 1920), (media_probe(qa['videos'][0]['file'])['width'],
                                        media_probe(qa['videos'][0]['file'])['height']))
        with self.assertRaises(FileExistsError):
            render(Path(p['plan']), approval, self.root / 'drafts')


if __name__ == '__main__':
    unittest.main()